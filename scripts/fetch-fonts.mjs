// Downloads the web fonts from Google Fonts once and self-hosts them, so the page needs no
// third-party requests before it can paint (Google's CSS -> gstatic font files was a two-hop,
// render-blocking chain). The font files are exactly the ones Google serves, so nothing looks different.
//
// Run after changing a family below or adding an icon to ICONS (keep it alphabetical):
//   node scripts/fetch-fonts.mjs
//
// Writes src/assets/fonts/*.woff2 (Vite hashes them for long caching), src/styles/fonts.css,
// and the <link rel="preload"> tags between the fonts:preload markers in index.html.

import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'

const TEXT_FONTS =
  'https://fonts.googleapis.com/css2?family=Caveat:wght@500;700&family=Noto+Sans+Georgian:wght@400..700&family=Noto+Serif+Georgian:wght@500..700&display=swap'

// Icon font subset: only these icons are in the downloaded file (~6 KB instead of ~4 MB)
const ICONS = [
  'arrow_back', 'arrow_forward', 'attach_file', 'bookmark', 'broken_image', 'calendar_today', 'check',
  'close', 'description', 'download', 'edit', 'favorite', 'ink_eraser', 'logout', 'mail', 'menu_book',
  'more_vert', 'open_in_new', 'person', 'photo_camera', 'picture_as_pdf', 'progress_activity', 'search',
  'upload', 'zoom_in', 'zoom_out',
]
const ICON_FONT = `https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:opsz,wght,FILL,GRAD@20..48,100..700,0..1,-50..200&icon_names=${[...ICONS].sort().join(',')}&display=block`

// Faces the first render waits for (main.tsx): preloaded so they download alongside the JS
const PRELOAD = [
  'caveat-latin',
  'noto-sans-georgian-georgian',
  'noto-sans-georgian-latin',
  'noto-serif-georgian-georgian',
  'noto-serif-georgian-latin',
  'material-symbols-outlined',
]

// Google picks the format and unicode-range subsets by user agent: ask as a current Chrome to get woff2
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36'

const FONT_DIR = new URL('../src/assets/fonts/', import.meta.url)
const CSS_FILE = new URL('../src/styles/fonts.css', import.meta.url)
const HTML_FILE = new URL('../index.html', import.meta.url)

const slug = (text) => text.toLowerCase().replace(/[^a-z0-9]+/g, '-')

async function get(url, as) {
  const response = await fetch(url, { headers: { 'User-Agent': UA } })
  if (!response.ok) throw new Error(`${response.status} for ${url}`)
  return as === 'text' ? response.text() : Buffer.from(await response.arrayBuffer())
}

await rm(FONT_DIR, { recursive: true, force: true })
await mkdir(FONT_DIR, { recursive: true })

const files = new Map() // remote url -> local file name
let css = ''

for (const source of [TEXT_FONTS, ICON_FONT]) {
  const sheet = await get(source, 'text')
  // Each @font-face may be preceded by a /* subset */ comment; the icon font has none
  css += sheet.replace(/(?:\/\* ([a-z0-9-]+) \*\/\s*)?@font-face \{([^}]*)\}/g, (block, subset, body) => {
    const family = /font-family: '([^']+)'/.exec(body)[1]
    const remote = /url\(([^)]+)\)/.exec(body)[1]
    if (!files.has(remote)) files.set(remote, `${slug(family)}${subset ? `-${subset}` : ''}.woff2`)
    return block.replace(remote, `../assets/fonts/${files.get(remote)}`)
  })
}

for (const [remote, name] of files) await writeFile(new URL(name, FONT_DIR), await get(remote))

const missing = PRELOAD.filter((name) => ![...files.values()].includes(`${name}.woff2`))
if (missing.length) throw new Error(`PRELOAD names not downloaded: ${missing.join(', ')}`)

await writeFile(
  CSS_FILE,
  `/* Generated by scripts/fetch-fonts.mjs from Google Fonts. Do not edit by hand, rerun the script. */\n\n${css.trim()}\n`,
)

const html = await readFile(HTML_FILE, 'utf8')
const eol = html.includes('\r\n') ? '\r\n' : '\n'
const preload = PRELOAD.map(
  (name) => `    <link rel="preload" href="/src/assets/fonts/${name}.woff2" as="font" type="font/woff2" crossorigin />`,
).join(eol)
const marked = /(<!-- fonts:preload -->)[\s\S]*?([ \t]*<!-- \/fonts:preload -->)/
if (!marked.test(html)) throw new Error('index.html is missing the <!-- fonts:preload --> markers')
await writeFile(HTML_FILE, html.replace(marked, (_, start, end) => `${start}${eol}${preload}${eol}${end}`))

console.log(`${files.size} font files, ${PRELOAD.length} preloaded`)
